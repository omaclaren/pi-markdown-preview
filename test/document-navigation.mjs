import assert from "node:assert/strict";
import { mkdtemp, writeFile, readFile, mkdir, symlink, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import puppeteer from "puppeteer-core";
import { createBrowserWatchServer } from "../shared/browser-watch-server.js";

const root = await mkdtemp(join(tmpdir(), "pmp-document-navigation-"));
const pageHtml = body => `<!doctype html><html><head><title>Source</title></head><body><main id="preview-root">${body}</main></body></html>`;
const pdf = await readFile(new URL("./gaussian_plot.pdf", import.meta.url));
let server, htmlWatch, browser;
try {
	await mkdir(join(root, "site"));
	await writeFile(join(root, "report.pdf"), pdf);
	await writeFile(join(root, "report.md"), "Report");
	await writeFile(join(root, "next.md"), "Next");
	await writeFile(join(root, "private.md"), "PRIVATE_FILE");
	await writeFile(join(root, "outside.js"), "window.outsideSecret='PRIVATE_FILE'");
	await symlink(join(root, "outside.js"), join(root, "site", "escape.js"));
	await writeFile(join(root, "site", "style.css"), "body { background: rgb(17, 34, 51); color: white; }");
	await writeFile(join(root, "site", "private.html"), "PRIVATE_HTML");
	await writeFile(join(root, "site", "data.json"), '{"private":true}');
	await writeFile(join(root, "site", "module.js"), "export const answer = 42;");
	await writeFile(join(root, "site", "app.js"), "import { answer } from './module.js'; document.querySelector('#answer').textContent = String(answer);");
	const authored = '<!doctype html><html><head><link rel="stylesheet" href="style.css"></head><body><h1>AUTHORED_PAGE</h1><p id="answer"></p><script type="module" src="app.js"></script></body></html>';
	await writeFile(join(root, "site", "page.html"), authored);
	const source = pageHtml('<h1>PRIVATE_RESPONSE</h1>' + '<p style="height:80px">Some source text</p>'.repeat(30) + '<p id="reading-anchor">Reading here</p><a id="report" href="report.md#details">Report</a> <a id="pdf" href="report.pdf#page=1">PDF</a> <a id="html" href="site/page.html">HTML</a>');
	server = await createBrowserWatchServer(source, root, { renderLocalDocument: async path => pageHtml(path.endsWith("next.md") ? '<h1>Next document</h1>' : '<h1 id="details">Report</h1><a id="next" href="next.md">Next document</a>') });
	const first = await fetch(server.url);
	const headers = { cookie: first.headers.get("set-cookie").split(";")[0] };
	const sourceHtml = await first.text();
	const route = id => new URL(sourceHtml.match(new RegExp(`id="${id}" href="([^"]+)"`))[1].replaceAll("&amp;", "&"), server.url);
	const pdfUrl = route("pdf");
	const unauthorized = await fetch(pdfUrl); assert.equal(unauthorized.status, 403); await unauthorized.text();
	const wrong = new URL(pdfUrl); wrong.searchParams.set("identity", "wrong");
	const conflict = await fetch(wrong, { headers }); assert.equal(conflict.status, 409); await conflict.text();
	const full = await fetch(pdfUrl, { headers });
	assert.ok(pdfUrl.pathname.endsWith("/report.pdf"), "native PDF viewers should see a human-readable filename");
	assert.equal(full.headers.get("content-type"), "application/pdf");
	assert.match(full.headers.get("content-disposition"), /^inline;/);
	assert.deepEqual(Buffer.from(await full.arrayBuffer()), pdf);
	const partial = await fetch(pdfUrl, { headers: { ...headers, range: "bytes=5-23" } });
	assert.equal(partial.status, 206);
	assert.equal(partial.headers.get("content-range"), `bytes 5-23/${pdf.length}`);
	assert.deepEqual(Buffer.from(await partial.arrayBuffer()), pdf.subarray(5, 24));
	const suffix = await fetch(pdfUrl, { headers: { ...headers, range: "bytes=-16" } });
	assert.equal(suffix.status, 206);
	assert.deepEqual(Buffer.from(await suffix.arrayBuffer()), pdf.subarray(-16));
	const invalid = await fetch(pdfUrl, { headers: { ...headers, range: `bytes=${pdf.length}-` } });
	assert.equal(invalid.status, 416); await invalid.text();
	const head = await fetch(pdfUrl, { method: "HEAD", headers });
	assert.equal(head.headers.get("content-length"), String(pdf.length));
	assert.equal((await head.text()).length, 0);

	console.log("PDF HTTP checks passed");
	browser = await puppeteer.launch({ executablePath: process.env.PUPPETEER_EXECUTABLE_PATH, headless: true, userDataDir: join(root, "browser") });
	const page = await browser.newPage();
	await page.setViewport({ width: 1000, height: 700 });
	await page.goto(server.url, { waitUntil: "load" });
	assert.equal(await page.$eval("#report", link => link.target), "");
	await page.$eval("#reading-anchor", anchor => anchor.scrollIntoView());
	const originalY = await page.evaluate(() => scrollY);
	await Promise.all([page.waitForNavigation(), page.click("#report")]);
	assert.equal(await page.$eval("#details", node => node.textContent), "Report");
	assert.equal(new URL(page.url()).hash, "#details");
	await Promise.all([page.waitForNavigation(), page.click("#next")]);
	assert.match(await page.content(), /Next document/);
	server.updateDocument(source.replace("PRIVATE_RESPONSE", "NEW_RESPONSE"));
	await page.goBack({ waitUntil: "load" });
	assert.equal(await page.$eval("#details", node => node.textContent), "Report");
	await page.goBack({ waitUntil: "load" });
	await page.waitForFunction(y => Math.abs(scrollY - y) < 80, {}, originalY);
	assert.equal(new URL(page.url()).searchParams.get("revision"), "1", "Back returns to the source revision, not a newer response");
	console.log("Same-tab/back navigation passed");
	// Browser-native middle click still opens a tab; no custom context menu.
	const popupPromise = browser.waitForTarget(target => target.type() === "page" && target !== page.target() && target.url().includes("/__pi_markdown_preview_document__/"), { timeout: 10000 }).then(target => target.page());
	await page.click("#report", { button: "middle" });
	const popup = await popupPromise;
	await popup.waitForSelector("#details");
	assert.equal(await popup.evaluate(() => window.opener), null);
	assert.match(await page.content(), /PRIVATE_RESPONSE/);
	await popup.close();

	console.log("Native new-tab navigation passed");
	await Promise.all([page.waitForNavigation(), page.click("#html")]);
	await page.waitForSelector("iframe");
	const frameElement = await page.$("iframe");
	const frame = await frameElement.contentFrame();
	await frame.waitForFunction(() => document.querySelector("#answer")?.textContent === "42");
	assert.equal(await frame.evaluate(() => getComputedStyle(document.body).backgroundColor), "rgb(17, 34, 51)");
	assert.notEqual(new URL(frame.url()).origin, new URL(page.url()).origin);
	assert.equal(await frame.evaluate(() => { try { return parent.document.body.textContent; } catch { return "blocked"; } }), "blocked");
	assert.equal(await frame.evaluate(() => { try { return document.cookie; } catch { return "blocked"; } }), "blocked");
	assert.equal(await frame.evaluate(async url => { try { return await (await fetch(url, { credentials: "include" })).text(); } catch { return "blocked"; } }, new URL("/", server.url).href), "blocked");
	const frameUrl = new URL(frame.url());
	const htmlResponse = await fetch(frameUrl);
	assert.match(htmlResponse.headers.get("content-security-policy"), /sandbox allow-scripts allow-popups;/);
	assert.doesNotMatch(htmlResponse.headers.get("content-security-policy"), /allow-same-origin/);
	await htmlResponse.text();
	for (const [name, status] of [["escape.js", 403], ["../private.md", 404], ["private.html", 415], ["data.json", 415], ["unknown.json", 404]]) {
		const response = await fetch(new URL(name, frameUrl)); assert.equal(response.status, status); await response.text();
	}
	await page.setViewport({ width: 320, height: 640, isMobile: true, hasTouch: true });
	assert.equal(await page.evaluate(() => innerWidth), 320);
	assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "HTML shell must fit a narrow mobile viewport");
	assert.ok(await page.$eval('nav[aria-label="Document navigation"] a', a => a.getBoundingClientRect().height >= 44));
	await page.click("summary");
	assert.ok(await page.$eval("pre", pre => pre.textContent.includes("<script type=\"module\"")));
	assert.equal(await page.$eval("iframe", node => getComputedStyle(node).display), "none");
	await Promise.all([page.waitForNavigation(), page.click('nav[aria-label="Document navigation"] a')]);
	assert.match(await page.content(), /PRIVATE_RESPONSE/);

	console.log("Isolated HTML checks passed");
	// A directly watched HTML file keeps authored snapshots, not raw HTML in the watch origin.
	htmlWatch = await createBrowserWatchServer(authored, join(root, "site"), { htmlFile: join(root, "site", "page.html") });
	await page.goto(htmlWatch.url, { waitUntil: "load" });
	await page.waitForSelector("iframe");
	await (await (await page.$("iframe")).contentFrame()).waitForSelector("#answer");
	htmlWatch.updateDocument(authored.replace("AUTHORED_PAGE", "UPDATED_PAGE"));
	await page.waitForFunction(() => new URL(location.href).searchParams.get("revision") === "2");
	await page.waitForSelector("iframe");
	await (await (await page.$("iframe")).contentFrame()).waitForFunction(() => document.querySelector("h1")?.textContent === "UPDATED_PAGE");
	await server.close();
	await assert.rejects(fetch(frameUrl), /fetch|connect/i);
	console.log("PASS same-tab/native-new-tab navigation, reading position, PDF ranges, isolated HTML/assets/source and cleanup");
} finally {
	await browser?.close();
	await htmlWatch?.close();
	await server?.close();
	await rm(root, { recursive: true, force: true });
}
